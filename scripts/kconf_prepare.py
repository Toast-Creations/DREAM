"""V1.22.0 hub preparation (no model). Two steps, each refusing to overwrite.
  kconf_prepare.py configs --hub HUB --model-from STAGE_JSON_1_21 --panel PANEL.json --guard GUARD.json
      copies the panel config and resource guard into HUB/config/ and writes stage-smoke.json / stage-main.json
      AFTER generation (needs HUB/data/*-calls.jsonl), with the model block byte-identical to the 1.21 stage config.
  kconf_prepare.py driver --hub HUB --code CODE_DIR
      writes HUB/run_kconf.sh from the template below (paths substituted)."""
import argparse
import json
import shutil
from pathlib import Path
import os
import sys

DRIVER = r'''#!/bin/bash
# V1.22.0 KEEP+ID confirmation collection driver (generated by kconf_prepare.py). Usage: run_kconf.sh
# freeze check -> GPU-idle check -> deadline record -> guard -> smoke (32 disjoint calls, watchdog) -> structural smoke
# check -> guard + feasibility -> main (2240, watchdog) -> stage check -> analysis -> final check -> DRIVER-SUCCESS.json.
# Every step's real exit status is checked; any failure exits nonzero and no success marker is written.
# retry_limit 0; no automatic resume. Every artifact is kept.
H=__HUB__
C=__CODE__
PY=__PY__
LOG=$H/driver.log
ctr() { __CTR__ "cd $C && $*"; }
step() { echo "$(date -Is) $*" >> $LOG; }
run() { ctr "$*" >> $LOG 2>&1; }
guard() { OUT=$(ctr "$PY -B scripts/kconf_guard.py $H $1 $DL"); RC=$?; echo "$OUT" | head -1 >> $LOG; REM=$(echo "$OUT" | tail -1); return $RC; }
stage() { local T=$((REM-120)); [ $T -gt 0 ] || { step "deadline too close for $1"; return 8; }
  __INHIBIT__ __CTR__ "cd $C && timeout -k 60 $T $PY -B __RUNNER__ --hub $H --stage $1 --config $H/config/stage-$1.json" >> $LOG 2>&1
  local RC=$?; step "stage $1 rc=$RC"; return $RC; }
[ -e $H/config/DEADLINE.json ] && { step "DEADLINE.json exists: no automatic resume"; exit 9; }
[ -e $H/DRIVER-SUCCESS.json ] && { step "DRIVER-SUCCESS.json exists: refusing to run"; exit 9; }
run "$PY -B -c 'import json,sys; sys.path.insert(0,\"src\"); from dream_core.ledger import release_source_hash as h; assert json.load(open(\"$H/config/FROZEN-PROTOCOL.json\"))[\"source_sha256\"]==h(\".\")'" || { step "freeze check FAILED"; exit 3; }
python3 -c "
import json,hashlib,pathlib,sys
H=pathlib.Path('$H'); f=json.load(open(H/'config/FROZEN-PROTOCOL.json'))
bad=[k for sec in ('design','config','data','phase0') for k,v in f[sec].items() if hashlib.sha256((H/sec/k).read_bytes()).hexdigest()!=v]
print('frozen-file mismatches',bad); sys.exit(1 if bad else 0)" >> $LOG 2>&1 || { step "frozen file check FAILED"; exit 3; }
step "freeze check ok (source + frozen files)"
if [ "__GPUCHECK__" = "1" ]; then
  # desktop compositor/browser GPU clients are allowed; any python compute process or > 3 GiB in use blocks the run
  USED=$(nvidia-smi --query-gpu=memory.used --format=csv,noheader,nounits 2>/dev/null | head -1)
  PYAPPS=$(nvidia-smi --query-compute-apps=process_name --format=csv,noheader 2>/dev/null | grep -ci python)
  { [ -n "$USED" ] && [ "$USED" -le 3072 ] && [ "$PYAPPS" = "0" ]; } || { step "GPU busy (used ${USED} MiB, python compute apps ${PYAPPS}): not starting"; exit 7; }
  step "GPU idle check ok (used ${USED} MiB)"
fi
NOW=$(date +%s); CEIL=$(python3 -c "import json;print(json.load(open('$H/config/RESOURCE-GUARD.json'))['ceiling_s'])")
DL=$((NOW+CEIL)); echo "{\"driver_start_epoch\": $NOW, \"deadline_epoch\": $DL, \"deadline_iso\": \"$(date -d @$DL -Is)\"}" > $H/config/DEADLINE.json
step "deadline $(date -d @$DL -Is)"
guard smoke || { step "guard smoke STOP"; exit 8; }
stage smoke || { step "smoke stage FAILED"; exit 10; }
run "$PY -B scripts/kconf_smoke_check.py $H" || { step "smoke check FAILED"; exit 4; }
step "smoke check ok"
guard main || { step "guard/feasibility main STOP"; exit 8; }
if ! stage main; then
  step "main stage FAILED"; run "$PY -B __ANALYZER__ --hub $H"; step "analysis (descriptive; must be INCOMPLETE) rc=$?"; exit 11
fi
run "$PY -B scripts/kconf_stage_check.py $H" || { step "stage check FAILED (incomplete)"; run "$PY -B __ANALYZER__ --hub $H"; step "analysis (incomplete) rc=$?"; exit 6; }
run "$PY -B __ANALYZER__ --hub $H" || { step "analysis FAILED"; exit 5; }
python3 -c "
import json,sys; a=json.load(open('$H/analysis/confirm/ANALYSIS.json'))
ok=a.get('status')=='COMPLETE' and 'qualification' in a and not a['infrastructure']['problems']
print('final check', a.get('status'), a['infrastructure']['problems'][:3]); sys.exit(0 if ok else 1)" >> $LOG 2>&1 || { step "final check FAILED (analysis not COMPLETE)"; exit 12; }
echo "{\"finished\": true, \"at\": \"$(date -Is)\", \"certifies\": [\"freeze\", \"guard\", \"smoke stage\", \"smoke check\", \"feasibility\", \"main stage\", \"stage check\", \"analysis\", \"final check\"]}" > $H/DRIVER-SUCCESS.json
step "done"
'''
PRODUCTION = {"__PY__": os.environ.get("DREAM_PY", sys.executable),  # public release: was a local venv path
              "__CTR__": "distrobox enter dream-research -- unshare -rn bash -c",
              "__INHIBIT__": 'systemd-inhibit --what=sleep:idle --who="DREAM kconf" --why="kconf stage" --mode=block',
              "__RUNNER__": "scripts/hold_run.py", "__ANALYZER__": "scripts/kconf_analyze.py", "__GPUCHECK__": "1"}


def render_driver(hub, code, **over):
    t = DRIVER.replace("__HUB__", str(Path(hub).resolve())).replace("__CODE__", str(Path(code).resolve()))
    for k, v in {**PRODUCTION, **over}.items():
        t = t.replace(k, v)
    return t


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["configs", "driver"])
    ap.add_argument("--hub", required=True)
    ap.add_argument("--model-from")
    ap.add_argument("--panel")
    ap.add_argument("--guard")
    ap.add_argument("--code")
    a = ap.parse_args()
    hub = Path(a.hub)
    cfgd = hub / "config"
    cfgd.mkdir(parents=True, exist_ok=True)
    if a.step == "configs":
        model = json.loads(Path(a.model_from).read_text())["model"]
        guard = json.loads(Path(a.guard).read_text())
        for k in ("total_attempts", "ceiling_s", "feasibility_slowdown", "main_overhead_s", "retry_limit"):
            if k not in guard:
                raise SystemExit(f"guard missing {k}")
        if guard["retry_limit"] != 0:
            raise SystemExit("retry_limit must be 0")
        for name, src in (("PANEL.json", a.panel), ("RESOURCE-GUARD.json", a.guard)):
            dst = cfgd / name
            if dst.exists() and dst.read_bytes() != Path(src).read_bytes():
                raise SystemExit(f"{dst} exists and differs")
            if not dst.exists():
                shutil.copyfile(src, dst)
        total = 0
        for st in ("smoke", "main"):
            calls = [json.loads(l)["call_id"] for l in (hub / "data" / f"{st}-calls.jsonl").read_text().splitlines() if l.strip()]
            total += len(calls)
            cfg = {"set": st, "order_seed": 0, "order": "as_committed", "max_input_tokens": 2048, "retry_limit": 0,
                   "model": model, "select": calls, "max_calls": len(calls), "max_seconds": guard["ceiling_s"]}
            p = cfgd / f"stage-{st}.json"
            if p.exists():
                raise SystemExit(f"{p} exists")
            p.write_text(json.dumps(cfg, indent=1) + "\n")
        if total > guard["total_attempts"]:
            raise SystemExit("scheduled calls exceed the attempt ceiling")
        print(json.dumps({"scheduled": total, "ceiling": guard["total_attempts"]}))
    else:
        p = hub / "run_kconf.sh"
        if p.exists():
            raise SystemExit(f"{p} exists")
        p.write_text(render_driver(hub, a.code))
        p.chmod(0o755)
        print(p)


if __name__ == "__main__":
    main()
