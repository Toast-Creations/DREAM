"""Teach verified synthetic answers to LoRA while steering selected activations.

This is teacher-forced causal language modeling: the full correct answer is
input, and the model is scored on predicting its tokens and EOS. It does not
train on answers generated by the model itself. The world loader/oracle must
validate references before this code receives them.

Lambda (``lam``) controls activation perturbation; eta scales the adapter learning
rate. Eta=0 still performs forward exposure and loss measurement, without an
optimizer or gradients. The base freeze and LoRA A/B allowlist are enforced by
the loader and plasticity module, not by the model's eval mode.

Timing limit: every step in one learn() call receives the same lambda. This
path does not apply the generation schedule flag or offer ramp/hold/taper
controls. Its time axes are example order and steps_per_example, not seconds.
"""
import json
import math
import torch
from dream_core.contracts import predictor_mask
from dream_core.modeling import render_chat
from dream_core.steering import MaskedSteerer, assert_no_dream_hooks
from .plasticity import adapter_parameters

SYSTEM = "Use only the stated synthetic world. Return one JSON object with only the key answer and the requested typed value."
CONCEPT_SYSTEM = "Answer in plain prose. Use what you know about this concept, including anything taught here."


def prepare_example(tokenizer, world, example, max_tokens):
    """Build one [1, sequence] input/label batch and its causal predictor mask.

    Prompt tokens provide context but have ignored labels (-100). The target
    tokens, including EOS, are supervised. Hugging Face causal-LM loss compares
    logits[t] to labels[t+1]; therefore the last prompt activation predicts the
    first answer token and must be steered. The final EOS activation predicts no
    scored token in this example and must not be selected merely for being last.

    Example: labels [-100, -100, A, B] need mask [False, True, True, False].
    Return the mask with a batch dimension matching the encoded tensors.
    """
    if "target_text" in example:
        # V1.3.3 concept worlds: a worded answer. Closed-book items have an empty
        # context, so the adapter must hold the concept to predict the target.
        # Rendered with thinking off (see render_chat) to match the direct target.
        taught = f"Taught material: {example['context']}\n" if example["context"] else ""
        prompt = f"Concept world {world['id']}: {world['concept']}.\n{taught}Question: {example['question']}"
        prefix = tokenizer.encode(render_chat(tokenizer, prompt, CONCEPT_SYSTEM, enable_thinking=False),
                                  add_special_tokens=False)
        target = tokenizer.encode(example["target_text"], add_special_tokens=False)
    else:
        prompt = (f"World {world['id']}. {world['description']}\nVerified rules or facts: {example['context']}\n"
                  f"Question: {example['question']}\nAnswer type: {example['answer_type']}.")
        prefix = tokenizer.encode(render_chat(tokenizer, prompt, SYSTEM), add_special_tokens=False)
        # render_chat already supplies the instruction model's special-token syntax.
        # Encode a canonical compact JSON target separately, then concatenate IDs;
        # no assumption is made that this equals tokenizing one concatenated string.
        target = tokenizer.encode(json.dumps({"answer": example["answer"]}, separators=(",", ":")), add_special_tokens=False)
    # Learning when to finish is part of the target. load_local_model requires a
    # defined EOS token before a real experiment can reach this function.
    target += [tokenizer.eos_token_id]
    ids = prefix + target
    if not prefix or len(ids) > max_tokens:
        # Never silently truncate a rule, question, target, or EOS to fit a cap:
        # that would change what the condition learned while hiding the change.
        raise ValueError("Training example exceeds cap or has no prompt; no silent truncation")
    labels = [-100] * len(prefix) + target
    mask = predictor_mask(labels)
    return {"input_ids": torch.tensor([ids], dtype=torch.long),
            "attention_mask": torch.ones((1,len(ids)), dtype=torch.long),
            "labels": torch.tensor([labels], dtype=torch.long)}, [mask]


def learn(model, tokenizer, world, cfg, vector, lam, eta, check=lambda: None):
    """Run one world's ordered learning/exposure phase and return step diagnostics.

    The caller supplies a validated config and a reset model. A new optimizer is
    constructed per call: Adam moments persist across steps inside this phase,
    but do not carry into another phase or independent trial. Each example gets
    a separate backward/update; this function does not accumulate gradients.

    ``check`` is the controller's cooperative budget check, called before each
    step. It can stop between operations but cannot interrupt a hung GPU kernel.
    An external supervisor is required for a hard wall-clock stop.

    This function removes its steering context and clears gradients; restoring
    adapter values after a completed or failed trial is the caller's job through
    reversible_trial(). Diagnostics describe delivery and do not establish an
    effect on held-out composition or identify its gradient mechanism.
    """
    # Re-check every parameter's trainability before handing tensors to an
    # optimizer. eval() alone would not protect frozen base parameters.
    parameters = list(adapter_parameters(model).values())
    # Eval mode disables dropout; gradients remain enabled. This is intentional.
    model.eval()
    optimizer_type = torch.optim.AdamW if cfg["adapter"]["optimizer"] == "adamw" else torch.optim.SGD
    # load_config restricts optimizer names to these two options. With eta=0,
    # omit optimizer creation entirely, including its state and potential updates.
    # Weight decay is explicitly zero, so it adds no separate parameter change.
    optimizer = None if eta == 0 else optimizer_type(parameters,
                lr=cfg["adapter"]["base_learning_rate"] * eta, weight_decay=0.0)
    device = model.get_input_embeddings().weight.device
    diagnostics = []
    try:
        for example in world["train"]:
            encoded, mask = prepare_example(tokenizer, world, example, cfg["limits"]["max_input_tokens"])
            if encoded["input_ids"].shape[1] > model.config.max_position_embeddings:
                raise ValueError("Training example exceeds model context window")
            encoded = {k:v.to(device) for k,v in encoded.items()}
            for step in range(cfg["adapter"]["steps_per_example"]):
                check()
                # A fresh gradient for this individual supervised example/step;
                # never reuse gradients left by the previous condition or step.
                model.zero_grad(set_to_none=True)
                # This is the constant-strength training path: generation=False
                # and schedule=False are defaults. All selected predictors in
                # this full teacher-forced forward receive the same scalar lam.
                with MaskedSteerer(model, cfg["steering"]["layer_index"], vector, lam, mask=mask):
                    with torch.set_grad_enabled(optimizer is not None):
                        # Training uses complete sequences, not a persistent KV
                        # cache. eval() disables dropout while autograd stays on
                        # exactly when an optimizer will perform an update.
                        output = model(**encoded, use_cache=False)
                        loss = output.loss
                    if not torch.isfinite(loss):
                        raise FloatingPointError("Non-finite training loss")
                    norm = None
                    if optimizer is not None:
                        # Backpropagate the target-only shifted loss through the
                        # perturbed forward. The steering vector is fixed, while
                        # only allowlisted LoRA parameters may receive updates.
                        loss.backward()
                        gradients = [p.grad for p in parameters if p.grad is not None]
                        if not gradients or any(not torch.isfinite(g).all() for g in gradients):
                            raise FloatingPointError("Missing or non-finite adapter gradient")
                        # The returned norm is PRE-clipping; the gradients used
                        # for step() have been clipped in place. A logged norm
                        # does not match update magnitudes between conditions,
                        # especially with AdamW's history-dependent rescaling.
                        norm = float(torch.nn.utils.clip_grad_norm_(parameters, cfg["adapter"]["max_grad_norm"], error_if_nonfinite=True))
                        optimizer.step()
                        if any(not torch.isfinite(p).all() for p in parameters):
                            raise FloatingPointError("Non-finite adapter after update")
                # One record per attempted successful forward/update step. The
                # counts describe this full teacher-forced sequence, not sampled
                # output length. For eta=0, norm=None and updated=False.
                diagnostics.append({"loss": float(loss.detach()), "gradient_norm_preclip": norm,
                    "updated": optimizer is not None, "supervised_predictions": sum(mask[0]),
                    "input_tokens": int(encoded["input_ids"].shape[1])})
    finally:
        # The inner context removes its hook even if forward/backward raises.
        # This final cleanup discards gradients and checks for a leaked context;
        # it intentionally does not pretend to roll adapter weights back itself.
        model.zero_grad(set_to_none=True)
        model.eval()
        assert_no_dream_hooks(model)
    return diagnostics
